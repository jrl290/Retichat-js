test("the invite parser trims exactly the vectors' invite_space (Unicode Zs and U+0009), and nothing JavaScript's trim() adds", () => {
    assert.deepEqual([...INVITE_SPACE], V.invite_space);
    for (const cp of V.invite_space) assert.ok(cp === 9 || /\p{Zs}/u.test(String.fromCodePoint(cp)), `U+${cp.toString(16)} is Zs or a tab`);
    // Every Unicode scalar but ',' around D: D is listed exactly when the
    // scalar is invite space (LXMF-rust the_invite_parser_trims_exactly_zs_and_tab).
    const wrong = [];
    for (let cp = 0; cp <= 0x10FFFF; cp++) {
        if (cp === 0x2C || (cp >= 0xD800 && cp <= 0xDFFF)) continue;
        const c = String.fromCodePoint(cp);
        const listed = inviteMembers(`${M},${c}${D}${c}${c},${c}`).includes(D);
        if (listed !== isInviteSpace(cp)) wrong.push(`U+${cp.toString(16).toUpperCase().padStart(4, "0")}`);
    }
    assert.deepEqual(wrong, [], "trimmed or kept against invite_space");
    // What JS trim() strips and the phones keep: never trimmed here.
    for (const c of ["\n", "\r\n", "\v", "\f", " ", " ", "﻿", "\u0085", "​"]) {
        assert.deepEqual(inviteMembers(`${M},${c}${D}${c}`), [M], JSON.stringify(c));
    }
});

