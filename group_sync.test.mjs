/** The fields map of a packed payload [timestamp, title, content, fields]: its offset. */
function fieldsAt(payload) {
    const top = readHead(payload, 0);
    let pos = top.end;
    for (let i = 0; i < 3; i++) pos = skipValue(payload, pos);
    return pos;
}

/** The offset of at_ms (0xFC's third element) in the fields map at `pos`. */
function atMsOffset(b, pos) {
    const map = readHead(b, pos);
    let p = map.end;
    for (let i = 0; i < map.count; i++) {
        const k = readHead(b, p);
        p = skipValue(b, p);
        if (k.kind === "int" && k.int === 0xFC) {
            let e = readHead(b, p).end;
            e = skipValue(b, e);
            e = skipValue(b, e);
            return e;
        }
        p = skipValue(b, p);
    }
    throw new Error("no 0xFC");
}

/** `bytes` with the int 64 at_ms (0xd3) at fields map `pos` written as the
 *  uint 64 (0xcf) rmpv and umsgpack write: the one byte the web's form
 *  differs in. */
function asUint64AtMs(bytes, pos) {
    const out = Buffer.from(bytes);
    const at = atMsOffset(out, pos);
    assert.equal(out[at], 0xd3, "the web writes at_ms as an int 64");
    out[at] = 0xcf;
    return out;
}

/** A G as the web packs it: D to D, empty title and content, `timestamp`. */
function packG(sync, timestamp) {
    const m = new LXMessage();
    m.timestamp = timestamp;
    m.sourceHash = hex(D);
    m.destinationHash = hex(D);
    m.title = "";
    m.content = "";
    m.fields = groupSyncFields(sync, D, DEVICE);
    return m.pack(distro, false);
}

