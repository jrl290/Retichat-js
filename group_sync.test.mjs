        const dest = blob.subarray(0, 16);
        assert.equal(dest.toString("hex"), D, s.name);
        const plaintext = distro.decrypt(blob.subarray(16));
        const packed = Buffer.concat([dest, plaintext]);
        assert.equal(packed.toString("hex"), s.packed_hex, `${s.name}: packed = blob[0:16] | plaintext`);
        const message = LXMessage.fromBytes(plaintext, dest, recall);
